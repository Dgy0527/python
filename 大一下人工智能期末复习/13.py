'''
13、题目简述
为了增强居民的节水意识，避免水资源的浪费，国家对居民水费实行阶梯定价。
以下是某市2022年居民水费阶梯定价的情况:
居民家庭月用水量（立方米）	单价（元/立方米）	阶梯定价策略
用水量 <= 10	             3元	用水量小，定价为阶梯价格的低位
10< 用水量 <= 20	         4元	用水量中等，定价为阶梯价格的中位
20< 用水量 <= 30	         5元	用水量较高，定价为阶梯价格的较高位
用水量 > 30	                 6元	用水量高，定价为阶梯价格的高位

程序说明
1.输入某个月的用水量
2.输出阶梯定价策略和单价
3.输出该月应缴的水费金额

样例输入
请输入本月用水量(立方米):15.88
样例输出
您的家庭月用水量中等，定价策略为阶梯价格的中位
您本月的水费单价为:4元/立方米
您本月应缴水费金额为:63.52元

'''

w=float(input('本月用水量(立方米):'))

if w>30:
    amount=round(w*6,2)
    print("您的家庭月用水量大,定价策略为阶梯价格的高位")
    print("您本月的水费单价为:6元/立方米")
elif w>20:
    amount=round(w*5,2)
    print("您的家庭月用水量较大,定价策略为阶梯价格的较高位")
    print("您本月的水费单价为:5元/立方米")
elif w>10:
    amount=round(w*4,2)
    print("您的家庭月用水量中等,定价策略为阶梯价格的中位")
    print("您本月的水费单价为:4元/立方米") 
else:
    amount=round(w*3,2)
    print("您的家庭月用水量小,定价策略为阶梯价格的低位")
    print("您本月的水费单价为:3元/立方米")
print('您本月应缴水费金额为:',amount,'元')


